def _read_mip(text: str) -> Model:
    model = Model(name="imported_mip")
    sense = "maximize" if "MAXIMIZE" in text else "minimize"
    for match in re.finditer(r"(\w+)\s*=\s*m\.add_var\(([^)]*)\)", text):
        name = match.group(1)
        args = match.group(2)
        domain = "binary" if "BINARY" in args else "integer" if "INTEGER" in args else "continuous"
        model.variables[name] = VarDecl(name=name, domain=domain, lower=_kw(args, "lb"), upper=_kw(args, "ub"))  # type: ignore[arg-type]
    obj = re.search(r"m\.objective\s*=\s*(.+)", text)
    if obj:
        model.objectives.append(Objective(name="obj", sense=sense, expr=_parse_expr(obj.group(1))))  # type: ignore[arg-type]
    for match in re.finditer(r"m\s*\+=\s*(.+)", text):
        relation, left, right = _relation(match.group(1))
        model.constraints.append(Constraint(name=f"c{len(model.constraints)+1}", kind="comparison", relation=relation, lhs=_parse_expr(left), rhs=_parse_expr(right)))  # type: ignore[arg-type]
    if not model.objectives:
        raise AxiomError("python-mip 文本里没有目标。", "The python-mip text has no objective.", code="import")
    return model


def sniff_python(text: str) -> str:
    """Pick a modeling library from generated Python when the extension is only `.py`."""
    if "import casadi" in text or "ca.SX.sym" in text:
        return "casadi"
    if "import linopy" in text or ".add_variables(" in text:
        return "linopy"
    if "docplex" in text or ".continuous_var(" in text or ".binary_var(" in text:
        return "docplex"
    if "gurobipy" in text or ".addVar(" in text:
        return "gurobipy"
    if "from mip import" in text or ".add_var(" in text:
        return "mip"
    if "import pulp" in text or "LpVariable" in text:
        return "pulp"
    if "import cvxpy" in text or "cp.Variable" in text:
        return "cvxpy"
    return "pyomo"


def _read_casadi(text: str) -> Model:
    model = Model(name="imported_casadi")
    order: list[str] = []
    for match in re.finditer(r"(\w+)\s*=\s*ca\.SX\.sym\(", text):
        name = match.group(1)
        if name in model.variables:
            continue
        order.append(name)
        model.variables[name] = VarDecl(name=name, domain="continuous")
    lowers = _bracket_numbers(r"lbx\s*=\s*\[([^\]]*)\]", text)
    uppers = _bracket_numbers(r"ubx\s*=\s*\[([^\]]*)\]", text)
    for index, name in enumerate(order):
        lower = _open_bound(lowers[index] if index < len(lowers) else None)
        upper = _open_bound(uppers[index] if index < len(uppers) else None)
        model.variables[name].lower = lower
        model.variables[name].upper = upper
    obj = re.search(r"objective\s*=\s*(.+)", text)
    sense = "minimize"
    expr = obj.group(1).strip() if obj else "0"
    if expr.startswith("-"):
        sense = "maximize"
        expr = expr[1:].strip()
    model.objectives.append(Objective(name="obj", sense=sense, expr=_parse_expr(expr)))  # type: ignore[arg-type]
    grown = re.search(r"(?m)^\s*g\s*=\s*ca\.vertcat\((.*)\)\s*$", text)
    if grown and grown.group(1).strip() not in {"", "ca.SX()"}:
        rows = _split_top(grown.group(1))
        lower_g = _bracket_numbers(r"lbg\s*=\s*\[([^\]]*)\]", text)
        upper_g = _bracket_numbers(r"ubg\s*=\s*\[([^\]]*)\]", text)
        for index, row in enumerate(rows):
            lhs, shift = _casadi_shift(row)
            lo = _open_bound(lower_g[index] if index < len(lower_g) else None)
            hi = _open_bound(upper_g[index] if index < len(upper_g) else None)
            if lo is not None and hi is not None and abs(lo - hi) <= 1e-9:
                relation = "=="
                rhs = shift + lo
                model.constraints.append(Constraint(name=f"c{index + 1}", kind="comparison", relation=relation, lhs=_parse_expr(lhs), rhs=_parse_expr(str(rhs))))  # type: ignore[arg-type]
                continue
            if hi is not None:
                model.constraints.append(Constraint(name=f"c{index + 1}", kind="comparison", relation="<=", lhs=_parse_expr(lhs), rhs=_parse_expr(str(shift + hi))))  # type: ignore[arg-type]
            if lo is not None:
                model.constraints.append(Constraint(name=f"c{index + 1}b", kind="comparison", relation=">=", lhs=_parse_expr(lhs), rhs=_parse_expr(str(shift + lo))))  # type: ignore[arg-type]
    return model


def _bracket_numbers(pattern: str, text: str) -> list[float | None]:
    match = re.search(pattern, text)
    if not match or not match.group(1).strip():
        return []
    return [_maybe(part) for part in match.group(1).split(",")]


def _open_bound(value: float | None) -> float | None:
    if value is None or abs(value) >= 1e19:
        return None
    return value


def _split_top(text: str) -> list[str]:
    parts: list[str] = []
    buf: list[str] = []
    depth = 0
    for char in text:
        if char == "(":
            depth += 1
        elif char == ")":
            depth = max(0, depth - 1)
        if char == "," and depth == 0:
            parts.append("".join(buf).strip())
            buf = []
        else:
            buf.append(char)
    tail = "".join(buf).strip()
    if tail:
        parts.append(tail)
    return [part for part in parts if part]


def _casadi_shift(expr: str) -> tuple[str, float]:
    depth = 0
    split_at = None
    index = 0
    while index < len(expr):
        char = expr[index]
        if char == "(":
            depth += 1
        elif char == ")":
            depth = max(0, depth - 1)
        elif depth == 0 and expr.startswith(" - ", index):
            split_at = index
        index += 1
    if split_at is None:
        return expr.strip(), 0.0
    left = expr[:split_at].strip()
    right = expr[split_at + 3 :].strip().strip("()")
    try:
        return left, float(right)
    except ValueError:
        return expr.strip(), 0.0


def _read_pyomo(text: str) -> Model:
    model = Model(name="imported_pyomo")
    for match in re.finditer(r"(?:model\.)?(\w+)\s*=\s*Var\((.*)\)\s*$", text, re.M):
        name = match.group(1)
        args = match.group(2)
        domain = "binary" if "Binary" in args else "integer" if "Integer" in args else "continuous"
        lower = upper = None
        bounds = re.search(r"bounds=\(([^,]*),\s*([^)]*)\)", args)
        if bounds:
            lower = _maybe(bounds.group(1))
            upper = _maybe(bounds.group(2))
        model.variables[name] = VarDecl(name=name, domain=domain, lower=lower, upper=upper)  # type: ignore[arg-type]
    rules: dict[str, str] = {}
    for match in re.finditer(r"def\s+(\w+)\s*\([^)]*\)\s*:\s*return\s+(.+)", text):
        rules[match.group(1)] = match.group(2).strip()
    sense = "maximize" if re.search(r"sense\s*=\s*maximize", text) else "minimize"
    objective = re.search(r"Objective\(\s*rule\s*=\s*(\w+)", text)
    if objective and objective.group(1) in rules:
        model.objectives.append(Objective(name="obj", sense=sense, expr=_parse_expr(rules[objective.group(1)])))  # type: ignore[arg-type]
    for match in re.finditer(r"Constraint\(\s*rule\s*=\s*(\w+)", text):
        rule = rules.get(match.group(1))
        if not rule or not any(symbol in rule for symbol in ("<=", ">=", "==", "=")):
            continue
        relation, left, right = _relation(rule)
        model.constraints.append(Constraint(name=f"c{len(model.constraints) + 1}", kind="comparison", relation=relation, lhs=_parse_expr(left), rhs=_parse_expr(right)))  # type: ignore[arg-type]
    if not model.objectives:
        raise AxiomError("Pyomo 文本里没有目标。", "The Pyomo text has no objective.", code="import")
    return model


def _read_python(text: str, kind: str) -> Model:
    if kind == "casadi":
        return _read_casadi(text)
    if kind == "pulp":
        return _read_python_vars(text, "imported_pulp", "LpVariable", "prob +=", "+=")
    if kind == "cvxpy":
        return _read_python_vars(text, "imported_cvxpy", "Variable", "Minimize", "constraints")
    if kind == "pyomo":
        return _read_pyomo(text)
    return _read_python_vars(text, "imported_pyomo", "Var", "Objective", "Constraint")


def _read_python_vars(text: str, model_name: str, var_token: str, obj_token: str, con_token: str) -> Model:
    model = Model(name=model_name)
    for match in re.finditer(rf"(\w+)\s*=\s*[^=\n]*{re.escape(var_token)}\(([^)]*)\)", text):
        name = match.group(1)
        args = match.group(2)
        domain = "binary" if "BINARY" in args or "binary" in args else "integer" if "INTEGER" in args or "integer" in args else "continuous"
        lower = _kw(args, "lb")
        if lower is None:
            lower = _kw(args, "lowBound")
        upper = _kw(args, "ub")
        if upper is None:
            upper = _kw(args, "upBound")
        if "bounds=(" in args.replace(" ", ""):
            bounds = re.search(r"bounds=\(([^,]*),([^)]*)\)", args)
            if bounds:
                lower = _maybe(bounds.group(1))
                upper = _maybe(bounds.group(2))
        if lower is None:
            lower = _kw(args, "lower")
        if upper is None:
            upper = _kw(args, "upper")
        model.variables[name] = VarDecl(name=name, domain=domain, lower=lower, upper=upper)  # type: ignore[arg-type]
    sense = "maximize" if re.search(r"LpMaximize|GRB\.MAXIMIZE|sense\s*=\s*maximize|sense\s*=\s*['\"]max|\bmaximize\b|MAXIMIZE", text, re.I) else "minimize"
    obj = re.search(r"(?:setObjective|add_objective|objective_rule|Minimize|Maximize|m\.maximize|m\.minimize)\((.+)\)", text)
    if obj:
        expr = obj.group(1).split(",")[0]
        if "MAXIMIZE" in obj.group(0) or "maximize" in obj.group(0):
            sense = "maximize"
        model.objectives.append(Objective(name="obj", sense=sense, expr=_parse_expr(expr)))  # type: ignore[arg-type]
    for match in re.finditer(r"(?:addConstr|add_constraint|add_constraints|constraints\.append)\((.+)\)", text):
        body = match.group(1).split(", name")[0].split(", ctname")[0]
        try:
            relation, left, right = _relation(body)
        except AxiomError:
            continue
        model.constraints.append(Constraint(name=f"c{len(model.constraints)+1}", kind="comparison", relation=relation, lhs=_parse_expr(left), rhs=_parse_expr(right)))  # type: ignore[arg-type]
    if not model.objectives:
        # PuLP `prob += expr` is the objective when it has no relation.
        for match in re.finditer(r"prob\s*\+=\s*(.+)", text):
            body = match.group(1)
            if any(symbol in body for symbol in ("<=", ">=", "==")):
                relation, left, right = _relation(body.split(",")[0])
                model.constraints.append(Constraint(name=f"c{len(model.constraints)+1}", kind="comparison", relation=relation, lhs=_parse_expr(left), rhs=_parse_expr(right)))  # type: ignore[arg-type]
            elif not model.objectives:
                model.objectives.append(Objective(name="obj", sense=sense, expr=_parse_expr(body.split(",")[0])))  # type: ignore[arg-type]
    if not model.objectives:
        raise AxiomError("文本里没有目标。", "The text has no objective.", code="import")
    return model


def _kw(args: str, name: str) -> float | None:
    match = re.search(rf"{name}\s*=\s*([^,)]+)", args)
    if not match:
        return None
    return _maybe(match.group(1))


def _maybe(text: str) -> float | None:
    text = text.strip()
    if text in {"None", "null"}:
        return None
    try:
        return float(text)
    except ValueError:
        return None


def _strip_comments(text: str) -> str:
    lines = []
    for raw in text.splitlines():
        if raw.strip().startswith("#"):
            continue
        lines.append(raw.split("#", 1)[0])
    return "\n".join(lines)


def _split_statements(text: str) -> list[str]:
    parts, buf, depth = [], [], 0
    for char in text:
        if char in "{[(":
            depth += 1
        elif char in "}])":
            depth = max(0, depth - 1)
        if char == ";" and depth == 0:
            statement = "".join(buf).strip()
            if statement:
                parts.append(statement)
            buf = []
        else:
            buf.append(char)
    tail = "".join(buf).strip()
    if tail:
        parts.append(tail)
    return parts


def _set_decl(statement: str) -> tuple[str, list[str]]:
    match = re.match(r"set\s+(\w+)\s*:=\s*(.+)", statement)
    if not match:
        raise AxiomError("无法读取集合声明。", "Could not read a set declaration.", code="import")
    elems = [part.strip().strip('"').strip("'") for part in match.group(2).replace(",", " ").split() if part.strip()]
    return match.group(1), elems


def _pairs(text: str) -> list[str]:
    return text.split()


def _ampl_var(model: Model, statement: str, sets: dict[str, list[str]]) -> None:
    body = statement[3:].strip()
    domain = "binary" if "binary" in body else "integer" if "integer" in body else "continuous"
    body = body.replace("binary", "").replace("integer", "")
    name = body.split()[0]
    name = name.split("{")[0]
    lower = upper = None
    if ">=" in body:
        lower = float(body.split(">=")[-1].split("<=")[0].strip())
    if "<=" in body:
        upper = float(body.split("<=")[-1].strip())
    if "{" in statement and name:
        index = re.search(r"\{([^}]*)\}", statement)
        set_names = [part.strip() for part in index.group(1).split(",")] if index else []
        elements = [sets.get(item, [item]) for item in set_names]
        for combo in _product(elements):
            key = name if not combo else f"{name}[{','.join(combo)}]"
            model.variables[key] = VarDecl(name=key, domain=domain, lower=lower, upper=upper)  # type: ignore[arg-type]
        return
    model.variables[name] = VarDecl(name=name, domain=domain, lower=lower, upper=upper)  # type: ignore[arg-type]


def _product(groups: list[list[str]]) -> list[tuple[str, ...]]:
    if not groups:
        return [()]
    rest = _product(groups[1:])
    return [(item, *tail) for item in groups[0] for tail in rest]


def _relation(expr: str) -> tuple[str, str, str]:
    return _split_relation_text(expr)


def _split_relation(body: str, relation: str) -> tuple[str, str]:
    symbol = "==" if relation == "==" else relation
    if symbol not in body and relation == "==" and "=" in body:
        symbol = "="
    left, right = body.split(symbol, 1)
    return left.strip(), right.strip()


def _split_relation_text(expr: str) -> tuple[str, str, str]:
    for symbol, relation in (("<=", "<="), (">=", ">="), ("==", "=="), ("=", "==")):
        if symbol in expr:
            left, right = expr.split(symbol, 1)
            return relation, left.strip(), right.strip()
    raise AxiomError(f"约束缺少比较符：{expr}", f"Constraint is missing a relation: {expr}", code="import")


def _jump_bounds(spec: str) -> tuple[float | None, float | None]:
    lower = upper = None
    match = re.search(r"([\d.eE+-]+)\s*<=", spec)
    if match:
        lower = float(match.group(1))
    match = re.search(r"<=\s*([\d.eE+-]+)", spec)
    if match:
        upper = float(match.group(1))
    return lower, upper


def _parse_expr(text: str, sets: dict[str, list[str]] | None = None) -> Expr:
    cleaned = text.strip().rstrip(";").strip()
    if cleaned.startswith("(") and cleaned.endswith(")") and _balanced(cleaned[1:-1]):
        cleaned = cleaned[1:-1].strip()
    sum_match = re.match(r"sum\s*\{([^}]*)\}\s*(.+)", cleaned)
    if sum_match and sets is not None:
        return _expand_sum(sum_match.group(1), sum_match.group(2), sets)
    return _parse_linear(cleaned)


def _balanced(text: str) -> bool:
    return text.count("(") == text.count(")")


def _expand_sum(spec: str, body: str, sets: dict[str, list[str]]) -> Expr:
    quants = []
    for part in spec.split(","):
        if " in " in part:
            index, set_name = part.split(" in ", 1)
            quants.append((index.strip(), set_name.strip()))
    groups = [sets.get(set_name, []) for _, set_name in quants]
    terms = []
    for combo in _product(groups):
        rendered = body
        for (index, _), value in zip(quants, combo, strict=True):
            rendered = re.sub(rf"\b{index}\b", value, rendered)
        terms.append(_parse_linear(rendered))
    expr = terms[0] if terms else const(0)
    for term in terms[1:]:
        expr = Expr(op="add", args=(expr, term))
    return expr


_TOKEN = re.compile(
    r"\s+"
    r"|(?P<num>(?:\d+\.\d*|\.\d+|\d+)(?:[eE][+-]?\d+)?)"
    r"|(?P<name>[A-Za-z_][A-Za-z0-9_]*(?:\.[A-Za-z_][A-Za-z0-9_]*)*(?:\[[^\]]*\])?)"
    r"|(?P<op>[+\-*/()])"
)


def _bare_name(name: str) -> str:
    if "." not in name:
        return name
    head, tail = name.split(".", 1)
    if head in {"m", "model", "cp", "pulp"}:
        return tail.split(".")[-1]
    return name


def _parse_linear(text: str) -> Expr:
    """Parse a scalar linear or quadratic expression, including parenthesized products."""
    tokens: list[tuple[str, str]] = []
    for match in _TOKEN.finditer(text):
        if match.group("num"):
            tokens.append(("num", match.group("num")))
        elif match.group("name"):
            tokens.append(("name", _bare_name(match.group("name"))))
        elif match.group("op"):
            tokens.append(("op", match.group("op")))
    pos = 0

    def peek() -> tuple[str, str] | None:
        return tokens[pos] if pos < len(tokens) else None

    def eat() -> tuple[str, str] | None:
        nonlocal pos
        token = peek()
        if token is not None:
            pos += 1
        return token

    def parse_expr() -> Expr:
        node = parse_term()
        while True:
            op = peek()
            if op is None or op[0] != "op" or op[1] not in "+-":
                return node
            eat()
            right = parse_term()
            node = Expr(op="add" if op[1] == "+" else "sub", args=(node, right))

    def parse_term() -> Expr:
        node = parse_factor()
        while True:
            op = peek()
            if op is None or op[0] != "op" or op[1] not in "*/":
                return node
            eat()
            right = parse_factor()
            if op[1] == "/" and right.op == "const" and right.value not in {None, 0}:
                node = Expr(op="mul", args=(node, const(1.0 / float(right.value))))
            else:
                node = Expr(op="mul", args=(node, right))

    def parse_factor() -> Expr:
        token = peek()
        if token is None:
            return const(0)
        if token[0] == "op" and token[1] in "+-":
            eat()
            inner = parse_factor()
            return inner if token[1] == "+" else Expr(op="neg", args=(inner,))
        if token[0] == "op" and token[1] == "(":
            eat()
            node = parse_expr()
            if peek() and peek()[1] == ")":
                eat()
            return node
        if token[0] == "num":
            eat()
            return const(float(token[1]))
        if token[0] == "name":
            eat()
            return ref(token[1])
        eat()
        return const(0)

    if not tokens:
        return const(0)
    return parse_expr()
