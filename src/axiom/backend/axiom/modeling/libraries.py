"""Import and export between AML and the usual modeling libraries.

Exporters write a scalar program from the flat model, which is what a solver
sees. Importers read that scalar form back, and also the indexed AMPL / GMPL
subset the studio already emits.
"""

from __future__ import annotations

import re

from axiom.errors import AxiomError
from axiom.modeling.flatten import flatten
from axiom.modeling.ir import Constraint, Expr, Model, Objective, VarDecl, const, ref


def emit_library(model: Model, target: str) -> str:
    flat = flatten(model)
    writer = {
        "gmpl": _gmpl,
        "zimpl": _zimpl,
        "opl": _opl,
        "gurobipy": _gurobipy,
        "docplex": _docplex,
        "linopy": _linopy,
        "mip": _python_mip,
        "casadi": _casadi,
    }.get(target)
    if writer is None:
        raise AxiomError(f"未知建模库 {target}。", f"Unknown modeling library {target}.", code="unknown_translator")
    return writer(flat)


def import_library(target: str, text: str) -> Model:
    key = target.lower().strip()
    if key in {"ampl", "gmpl", "mod"}:
        return _read_ampl(text)
    if key == "gams":
        return _read_gams(text)
    if key in {"jump", "julia"}:
        return _read_jump(text)
    if key == "zimpl":
        return _read_zimpl(text)
    if key == "opl":
        return _read_opl(text)
    if key == "gurobipy":
        return _read_gurobi(text)
    if key == "docplex":
        return _read_docplex(text)
    if key == "linopy":
        return _read_linopy(text)
    if key in {"mip", "python-mip"}:
        return _read_mip(text)
    if key in {"pyomo", "pulp", "cvxpy", "casadi"}:
        return _read_python(text, key)
    raise AxiomError(f"不能导入 {target}。", f"Cannot import {target}.", code="import")


def _names(flat) -> dict[str, str]:
    used: set[str] = set()
    mapping = {}
    for var in flat.variables:
        base = "".join(ch if ch.isalnum() or ch == "_" else "_" for ch in var.key)
        if not base or base[0].isdigit():
            base = "v_" + base
        name = base
        n = 2
        while name in used:
            name = f"{base}_{n}"
            n += 1
        used.add(name)
        mapping[var.key] = name
    return mapping


def _expr(coeffs: dict[str, float], names: dict[str, str], constant: float = 0.0) -> str:
    parts = []
    for key, coef in coeffs.items():
        if abs(coef) < 1e-12:
            continue
        name = names.get(key, key)
        parts.append(name if abs(abs(coef) - 1) < 1e-12 and coef > 0 else f"({_num(coef)})*{name}")
    if abs(constant) > 1e-12 or not parts:
        parts.append(_num(constant))
    return " + ".join(parts)


def _num(value: float) -> str:
    if float(value).is_integer() and abs(value) < 1e15:
        return str(int(value))
    return format(float(value), ".12g")


def _header(flat, names) -> list[str]:
    return []


def _gmpl(flat) -> str:
    names = _names(flat)
    lines = [f"# GMPL generated by Axiom from {flat.name}"]
    for var in flat.variables:
        kind = " integer" if var.domain == "integer" else " binary" if var.domain == "binary" else ""
        lines.append(f"var {names[var.key]}{kind}{_bounds(var.lower, var.upper)};")
    lines.append(f"{flat.sense} objective: {_expr(flat.objective, names, flat.objective_const)};")
    for con in flat.constraints:
        lines.append(f"s.t. { _clean(con.key) }: {_expr(con.coeffs, names)} {con.sense if con.sense != '==' else '='} {_num(con.rhs)};")
    lines.append("")
    return "\n".join(lines)


def _zimpl(flat) -> str:
    names = _names(flat)
    lines = [f"# ZIMPL generated by Axiom from {flat.name}"]
    for var in flat.variables:
        kind = " integer" if var.domain == "integer" else " binary" if var.domain == "binary" else ""
        lines.append(f"var {names[var.key]}{kind}{_bounds(var.lower, var.upper)};")
    lines.append(f"{flat.sense} objective: {_expr(flat.objective, names, flat.objective_const)};")
    for con in flat.constraints:
        lines.append(f"subto {_clean(con.key)}: {_expr(con.coeffs, names)} {con.sense if con.sense != '==' else '='} {_num(con.rhs)};")
    lines.append("")
    return "\n".join(lines)


def _opl(flat) -> str:
    names = _names(flat)
    lines = [f"// OPL generated by Axiom from {flat.name}"]
    for var in flat.variables:
        kind = "int+" if var.domain == "integer" else "boolean" if var.domain == "binary" else "float+"
        lines.append(f"dvar {kind} {names[var.key]};")
    lines.append(f"{flat.sense} {_expr(flat.objective, names, flat.objective_const)};")
    lines.append("subject to {")
    for con in flat.constraints:
        lines.append(f"  {_expr(con.coeffs, names)} {con.sense if con.sense != '==' else '='} {_num(con.rhs)};")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def _gurobipy(flat) -> str:
    names = _names(flat)
    lines = [
        '"""Generated by Axiom. Requires an installed gurobipy license."""',
        "import gurobipy as gp",
        "from gurobipy import GRB",
        "",
        f"m = gp.Model({flat.name!r})",
        "m.Params.OutputFlag = 0",
    ]
    for var in flat.variables:
        vtype = {"continuous": "GRB.CONTINUOUS", "integer": "GRB.INTEGER", "binary": "GRB.BINARY"}[var.domain]
        lb = "None" if var.lower is None else _num(var.lower)
        ub = "None" if var.upper is None else _num(var.upper)
        lines.append(f"{names[var.key]} = m.addVar(lb={lb}, ub={ub}, vtype={vtype}, name={names[var.key]!r})")
    sense = "GRB.MAXIMIZE" if flat.sense == "maximize" else "GRB.MINIMIZE"
    lines.append(f"m.setObjective({_expr(flat.objective, names, flat.objective_const)}, {sense})")
    for con in flat.constraints:
        lines.append(f"m.addConstr({_expr(con.coeffs, names)} {con.sense if con.sense != '==' else '=='} {_num(con.rhs)}, name={_clean(con.key)!r})")
    lines += ["m.optimize()", "objective_value = m.ObjVal", ""]
    return "\n".join(lines)


def _docplex(flat) -> str:
    names = _names(flat)
    lines = [
        '"""Generated by Axiom. Requires an installed CPLEX license."""',
        "from docplex.mp.model import Model",
        "",
        f"m = Model(name={flat.name!r})",
    ]
    for var in flat.variables:
        if var.domain == "binary":
            lines.append(f"{names[var.key]} = m.binary_var(name={names[var.key]!r})")
        elif var.domain == "integer":
            lines.append(f"{names[var.key]} = m.integer_var(lb={_bound(var.lower)}, ub={_bound(var.upper)}, name={names[var.key]!r})")
        else:
            lines.append(f"{names[var.key]} = m.continuous_var(lb={_bound(var.lower)}, ub={_bound(var.upper)}, name={names[var.key]!r})")
    method = "maximize" if flat.sense == "maximize" else "minimize"
    lines.append(f"m.{method}({_expr(flat.objective, names, flat.objective_const)})")
    for con in flat.constraints:
        lines.append(f"m.add_constraint({_expr(con.coeffs, names)} {con.sense if con.sense != '==' else '=='} {_num(con.rhs)}, ctname={_clean(con.key)!r})")
    lines += ["solution = m.solve()", "objective_value = solution.objective_value", ""]
    return "\n".join(lines)


def _linopy(flat) -> str:
    names = _names(flat)
    lines = [
        '"""Generated by Axiom for linopy."""',
        "import linopy",
        "",
        "m = linopy.Model()",
    ]
    for var in flat.variables:
        lb = "None" if var.lower is None else _num(var.lower)
        ub = "None" if var.upper is None else _num(var.upper)
        binary = ", binary=True" if var.domain == "binary" else ", integer=True" if var.domain == "integer" else ""
        lines.append(f"{names[var.key]} = m.add_variables(lower={lb}, upper={ub}{binary}, name={names[var.key]!r})")
    for con in flat.constraints:
        lines.append(f"m.add_constraints({_expr(con.coeffs, names)} {con.sense if con.sense != '==' else '=='} {_num(con.rhs)}, name={_clean(con.key)!r})")
    sense = "max" if flat.sense == "maximize" else "min"
    lines.append(f"m.add_objective({_expr(flat.objective, names, flat.objective_const)}, sense={sense!r})")
    lines.append("")
    return "\n".join(lines)


def _python_mip(flat) -> str:
    names = _names(flat)
    lines = [
        '"""Generated by Axiom for python-mip."""',
        "from mip import BINARY, CONTINUOUS, INTEGER, MAXIMIZE, MINIMIZE, Model, xsum",
        "",
        f"m = Model(sense={'MAXIMIZE' if flat.sense == 'maximize' else 'MINIMIZE'})",
    ]
    for var in flat.variables:
        kind = {"continuous": "CONTINUOUS", "integer": "INTEGER", "binary": "BINARY"}[var.domain]
        lb = "0" if var.lower is None else _num(var.lower)
        ub = "None" if var.upper is None else _num(var.upper)
        lines.append(f"{names[var.key]} = m.add_var(name={names[var.key]!r}, lb={lb}, ub={ub}, var_type={kind})")
    lines.append(f"m.objective = {_expr(flat.objective, names, flat.objective_const)}")
    for con in flat.constraints:
        lines.append(f"m += {_expr(con.coeffs, names)} {con.sense if con.sense != '==' else '=='} {_num(con.rhs)}")
    lines += ["m.optimize()", "objective_value = m.objective_value", ""]
    return "\n".join(lines)


def _casadi(flat) -> str:
    names = _names(flat)
    lines = [
        '"""Generated by Axiom for CasADi."""',
        "import casadi as ca",
        "",
    ]
    syms = []
    for var in flat.variables:
        lines.append(f"{names[var.key]} = ca.SX.sym({names[var.key]!r})")
        syms.append(names[var.key])
    sign = "-" if flat.sense == "maximize" else ""
    lines.append(f"objective = {sign}({_expr(flat.objective, names, flat.objective_const)})")
    rows = [f"({_expr(con.coeffs, names)}) - ({_num(con.rhs)})" for con in flat.constraints]
    g = "ca.vertcat(" + ", ".join(rows) + ")" if rows else "ca.SX()"
    lines.append(f"g = {g}")
    lines.append(f"x = ca.vertcat({', '.join(syms)})")
    lines.append('nlp = {"x": x, "f": objective, "g": g}')
    lines.append('solver = ca.nlpsol("axiom", "ipopt", nlp)')
    lb = ", ".join("0" if var.lower is None else _num(var.lower) for var in flat.variables)
    ub = ", ".join("1e20" if var.upper is None else _num(var.upper) for var in flat.variables)
    lbg, ubg = [], []
    for con in flat.constraints:
        if con.sense == "<=":
            lbg.append("-1e20")
            ubg.append("0")
        elif con.sense == ">=":
            lbg.append("0")
            ubg.append("1e20")
        else:
            lbg.append("0")
            ubg.append("0")
    lines.append(f"solution = solver(x0=0, lbx=[{lb}], ubx=[{ub}], lbg=[{', '.join(lbg)}], ubg=[{', '.join(ubg)}])")
    lines.append("objective_value = float(solution['f'])")
    lines.append("")
    return "\n".join(lines)


def _bounds(lower, upper) -> str:
    parts = ""
    if lower is not None:
        parts += f" >= {_num(lower)}"
    if upper is not None:
        parts += f" <= {_num(upper)}"
    return parts


def _bound(value) -> str:
    return "None" if value is None else _num(value)


def _clean(name: str) -> str:
    cleaned = "".join(ch if ch.isalnum() or ch == "_" else "_" for ch in name)
    return cleaned[:60] or "c"


def _model_from_scalar(name: str, variables: list[tuple], sense: str, objective: str, rows: list[tuple[str, str]]) -> Model:
    model = Model(name=name)
    for var_name, domain, lower, upper in variables:
        model.variables[var_name] = VarDecl(name=var_name, domain=domain, lower=lower, upper=upper)  # type: ignore[arg-type]
    model.objectives.append(Objective(name="obj", sense=sense, expr=_parse_expr(objective)))  # type: ignore[arg-type]
    for index, (relation, body) in enumerate(rows, start=1):
        left, right = _split_relation(body, relation)
        model.constraints.append(Constraint(name=f"c{index}", kind="comparison", relation=relation, lhs=_parse_expr(left), rhs=_parse_expr(right)))  # type: ignore[arg-type]
    return model


def _read_ampl(text: str) -> Model:
    body = _strip_comments(text)
    statements = _split_statements(body)
    model = Model(name="imported_ampl")
    sets: dict[str, list[str]] = {}
    pending_params: dict[str, list[str]] = {}
    data = False
    for statement in statements:
        if statement.lower() == "data":
            data = True
            continue
        head = statement.split(None, 1)[0].lower() if statement.split() else ""
        if head == "set":
            name, elems = _set_decl(statement)
            sets[name] = elems
            continue
        if head == "param" and not data:
            match = re.match(r"param\s+(\w+)\s*:=\s*(.+)", statement)
            if match and "{" not in statement.split(":=")[0]:
                # scalar, filled as a constant expression later via replacement
                sets[f"__param_{match.group(1)}"] = [match.group(2).strip()]
            else:
                indexed = re.match(r"param\s+(\w+)\s*\{([^}]*)\}", statement)
                if indexed:
                    pending_params[indexed.group(1)] = [part.strip() for part in indexed.group(2).split(",")]
            continue
        if head == "param" and data:
            match = re.match(r"param\s+(\w+)\s*:=\s*(.+)", statement)
            if match:
                pending_params[match.group(1)] = _pairs(match.group(2))
            continue
        if head == "var":
            _ampl_var(model, statement, sets)
            continue
        if head in {"minimize", "maximize"}:
            sense, expr = statement.split(":", 1)
            sense_name = "maximize" if sense.lower().startswith("maximize") else "minimize"
            model.objectives.append(Objective(name="obj", sense=sense_name, expr=_parse_expr(expr, sets)))  # type: ignore[arg-type]
            continue
        if head in {"s.t.", "subject"} or statement.lower().startswith("s.t.") or statement.lower().startswith("subto"):
            name, expr = statement.split(":", 1)
            relation, left, right = _relation(expr)
            model.constraints.append(Constraint(name=_clean(name.split()[-1]), kind="comparison", relation=relation, lhs=_parse_expr(left, sets), rhs=_parse_expr(right, sets)))  # type: ignore[arg-type]
    if not model.objectives:
        raise AxiomError("AMPL 文本里没有目标。", "The AMPL text has no objective.", code="import")
    return model


def _read_gams(text: str) -> Model:
    # Scalar GAMS and the studio's indexed export both use `name.. lhs =e= rhs`.
    model = Model(name="imported_gams")
    for raw in text.splitlines():
        if raw.lstrip().startswith("*"):
            continue
        line = raw.strip()
        if not line or line.startswith("$"):
            continue
        if line.lower().startswith("variables"):
            continue
        if line.lower().startswith("positive variable"):
            name = line.split()[-1].rstrip(";")
            if name in model.variables:
                model.variables[name].lower = 0.0
            continue
        if line.lower().startswith("binary variable"):
            name = line.split()[-1].rstrip(";")
            if name in model.variables:
                model.variables[name].domain = "binary"
            continue
        compact = line.replace(" ", "")
        if ".." in line and any(token in compact for token in ("=e=", "=l=", "=g=")):
            left, right = line.split("..", 1)
            name = left.strip()
            body = right.strip().rstrip(";")
            compact = body.replace(" ", "")
            if "=e=" in body:
                lhs, rhs = body.split("=e=", 1)
                relation = "=="
            elif "=l=" in body:
                lhs, rhs = body.split("=l=", 1)
                relation = "<="
            elif "=g=" in body:
                lhs, rhs = body.split("=g=", 1)
                relation = ">="
            else:
                continue
            if relation == "==" and (name == "objective" or lhs.strip() in {"axiom_obj", "objective"}):
                model.objectives.append(Objective(name="obj", sense="minimize", expr=_parse_expr(rhs)))  # type: ignore[arg-type]
            else:
                model.constraints.append(Constraint(name=_clean(name), kind="comparison", relation=relation, lhs=_parse_expr(lhs), rhs=_parse_expr(rhs)))  # type: ignore[arg-type]
        elif line.lower().startswith("solve ") and "maximizing" in line.lower():
            if model.objectives:
                model.objectives[0].sense = "maximize"
    declared = set()
    for raw in text.splitlines():
        if raw.strip().lower().startswith("variables"):
            for name in raw.split(None, 1)[1].rstrip(";").split(","):
                name = name.strip()
                if name and name != "axiom_obj":
                    declared.add(name)
    for name in declared:
        if name not in model.variables:
            model.variables[name] = VarDecl(name=name, domain="continuous", lower=None, upper=None)
    for raw in text.splitlines():
        if raw.lstrip().startswith("*"):
            continue
        line = raw.strip()
        if line.lower().startswith("positive variable"):
            name = line.split()[-1].rstrip(";")
            if name in model.variables and model.variables[name].lower is None:
                model.variables[name].lower = 0.0
        bound = re.match(r"(\w+)\.lo\s*=\s*([-+0-9.eE]+)", line)
        if bound and bound.group(1) in model.variables:
            model.variables[bound.group(1)].lower = float(bound.group(2))
    if not model.objectives:
        raise AxiomError("GAMS 文本里没有目标。", "The GAMS text has no objective.", code="import")
    return model


def _read_jump(text: str) -> Model:
    model = Model(name="imported_jump")
    for raw in text.splitlines():
        line = raw.split("#", 1)[0].strip()
        if line.startswith("@variable"):
            body = line[len("@variable") :].strip().lstrip("(").rstrip(")")
            parts = [part.strip() for part in body.split(",")]
            spec = parts[-1] if parts[0] == "model" else parts[0]
            domain = "binary" if "Bin" in line else "integer" if "Int" in line else "continuous"
            name = spec.strip()
            lower, upper = _jump_bounds(name)
            name = re.sub(r"^[\d\.\-]+\s*<=\s*", "", name)
            name = re.sub(r"\s*<=\s*[\d\.\-]+$", "", name).strip()
            model.variables[name] = VarDecl(name=name, domain=domain, lower=lower, upper=upper)  # type: ignore[arg-type]
        elif line.startswith("@objective"):
            body = line.split(",", 2)
            sense = "maximize" if "Max" in body[1] else "minimize"
            model.objectives.append(Objective(name="obj", sense=sense, expr=_parse_expr(body[2].rstrip(")"))))  # type: ignore[arg-type]
        elif line.startswith("@constraint"):
            body = line[len("@constraint") :].strip().lstrip("(").rstrip(")")
            parts = [part.strip() for part in body.split(",")]
            expr = parts[-1]
            relation, left, right = _relation(expr)
            model.constraints.append(Constraint(name=f"c{len(model.constraints)+1}", kind="comparison", relation=relation, lhs=_parse_expr(left), rhs=_parse_expr(right)))  # type: ignore[arg-type]
    if not model.objectives:
        raise AxiomError("JuMP 文本里没有目标。", "The JuMP text has no objective.", code="import")
    return model


