def _read_opl(text: str) -> Model:
    model = Model(name="imported_opl")
    for raw in text.splitlines():
        line = raw.split("//", 1)[0].strip()
        if line.startswith("dvar"):
            parts = line.rstrip(";").split()
            kind = parts[1]
            name = parts[2]
            domain = "binary" if kind == "boolean" else "integer" if kind.startswith("int") else "continuous"
            lower = 0.0 if kind.endswith("+") or domain == "binary" else None
            upper = 1.0 if domain == "binary" else None
            model.variables[name] = VarDecl(name=name, domain=domain, lower=lower, upper=upper)  # type: ignore[arg-type]
        elif line.startswith("maximize") or line.startswith("minimize"):
            sense, expr = line.split(None, 1)
            model.objectives.append(Objective(name="obj", sense=sense, expr=_parse_expr(expr.rstrip(";"))))  # type: ignore[arg-type]
        elif any(symbol in line for symbol in ("<=", ">=", "=")) and not line.startswith("subject") and line not in {"{"}:
            relation, left, right = _relation(line.rstrip(";"))
            model.constraints.append(Constraint(name=f"c{len(model.constraints)+1}", kind="comparison", relation=relation, lhs=_parse_expr(left), rhs=_parse_expr(right)))  # type: ignore[arg-type]
    if not model.objectives:
        raise AxiomError("OPL 文本里没有目标。", "The OPL text has no objective.", code="import")
    return model


