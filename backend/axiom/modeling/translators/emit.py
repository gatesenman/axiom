"""Readable source export for Pyomo, PuLP, OR-Tools, CVXPY, AMPL, GAMS, and JuMP."""

from __future__ import annotations

from axiom.errors import AxiomError, NonlinearError
from axiom.modeling.flatten import linearize_expr
from axiom.modeling.ir import Expr, Model, Quantifier

_PYTHON = {"pyomo", "pulp", "ortools", "cvxpy"}
_LINEAR_ONLY = {"pulp", "ortools"}


def emit_source(model: Model, target: str) -> str:
    if target in _LINEAR_ONLY and _nonlinear(model):
        raise AxiomError(
            f"{target} 导出只支持线性模型。",
            f"The {target} exporter only supports linear models.",
            code="nonlinear",
        )
    if target == "pyomo":
        return _pyomo(model)
    if target == "pulp":
        return _pulp(model)
    if target == "ortools":
        return _ortools(model)
    if target == "cvxpy":
        return _cvxpy(model)
    if target == "ampl":
        return _ampl(model)
    if target == "gams":
        return _gams(model)
    if target == "jump":
        return _jump(model)
    raise AxiomError(f"未知文本导出 {target}。", f"Unknown text export {target}.", code="unknown_translator")


def _nonlinear(model: Model) -> bool:
    try:
        for obj in model.objectives:
            linearize_expr(model, obj.expr, {}, {})
        for con in model.constraints:
            if con.kind != "comparison" or con.lhs is None or con.rhs is None:
                continue
            env: dict[str, str] = {}
            # Linearity does not depend on a specific index assignment when the
            # expression shape is uniform, so the first tuple is enough.
            from axiom.modeling.ir import cartesian

            combos = cartesian(model, [q.set_name for q in con.quants]) or [()]
            names = [q.index for q in con.quants]
            qmap = {q.index: q.set_name for q in con.quants}
            env = dict(zip(names, combos[0], strict=True)) if names else {}
            linearize_expr(model, con.lhs, env, qmap)
            linearize_expr(model, con.rhs, env, qmap)
    except NonlinearError:
        return True
    return False


def _pyomo(model: Model) -> str:
    lines = [
        '"""Generated by Axiom from the AML model. Pyomo concrete model."""',
        "from pyomo.environ import (",
        "    Binary, ConcreteModel, Constraint, Integers, Objective, Param, Reals,",
        "    Set, Var, maximize, minimize, value,",
        ")",
        "",
        f"model = ConcreteModel(name={model.name!r})",
    ]
    for decl in model.sets.values():
        lines.append(f"model.{decl.name} = Set(initialize={_pylist(decl.elements)})")
    lines.extend(_prev_pyomo(model))
    for decl in model.parameters.values():
        if not decl.index_sets:
            lines.append(f"model.{decl.name} = Param(initialize={_num(decl.values.get((), 0.0))})")
        else:
            index = ", ".join(f"model.{name}" for name in decl.index_sets)
            default = "" if decl.default is None else f", default={_num(decl.default)}"
            lines.append(f"model.{decl.name} = Param({index}, initialize={_pydict(decl.values)}{default})")
    for decl in model.variables.values():
        index = ", ".join(f"model.{name}" for name in decl.index_sets)
        prefix = f"{index}, " if index else ""
        domain = {"continuous": "Reals", "integer": "Integers", "binary": "Binary"}[decl.domain]
        lower = "None" if decl.lower is None else _num(decl.lower)
        upper = "None" if decl.upper is None else _num(decl.upper)
        lines.append(f"model.{decl.name} = Var({prefix}domain={domain}, bounds=({lower}, {upper}))")
    sense, expression = _objective(model, "pyomo")
    lines.append(f"def objective_rule(m):")
    lines.append(f"    return {expression}")
    lines.append(f"model.objective = Objective(rule=objective_rule, sense={sense})")
    for con in model.constraints:
        args = ", ".join(["m", *[q.index for q in con.quants]])
        indexes = ", ".join(f"model.{q.set_name}" for q in con.quants)
        header = f"model.{con.name} = Constraint({indexes}, rule={con.name}_rule)" if indexes else f"model.{con.name} = Constraint(rule={con.name}_rule)"
        lines.append(f"def {con.name}_rule({args}):")
        lines.append(f"    return {_comparison(con, 'pyomo', {q.index for q in con.quants}, {q.index: q.set_name for q in con.quants})}")
        lines.append(header)
    lines.append("")
    lines.append('if __name__ == "__main__":')
    lines.append('    print("Pyomo model", model.name, "is built.")')
    lines.append("")
    return "\n".join(lines)


def _pulp(model: Model) -> str:
    lines = [
        '"""Generated by Axiom. Solves with PuLP CBC."""',
        "import pulp",
        "",
    ]
    lines.extend(_python_sets(model))
    lines.extend(_prev_python(model))
    lines.extend(_python_params(model))
    for decl in model.variables.values():
        cat = {"continuous": "pulp.LpContinuous", "integer": "pulp.LpInteger", "binary": "pulp.LpBinary"}[decl.domain]
        low = "None" if decl.lower is None else _num(decl.lower)
        up = "None" if decl.upper is None else _num(decl.upper)
        if not decl.index_sets:
            lines.append(f"{decl.name} = pulp.LpVariable({decl.name!r}, lowBound={low}, upBound={up}, cat={cat})")
        else:
            lines.append(f"{decl.name} = {{}}")
            loops = _loops(decl.index_sets)
            lines.extend(loops)
            key = _key([_index_name(name) for name in decl.index_sets])
            indent = "    " * len(decl.index_sets)
            lines.append(f'{indent}{decl.name}[{key}] = pulp.LpVariable(f"{decl.name}_' + "{" + key + '}", lowBound=' + low + f", upBound={up}, cat={cat})")
    sense = "pulp.LpMaximize" if _objective(model, "pulp")[0] == "maximize" else "pulp.LpMinimize"
    # recompute sense properly
    obj_sense, expression = _objective(model, "pulp")
    sense = "pulp.LpMaximize" if obj_sense == "maximize" else "pulp.LpMinimize"
    lines.append(f"prob = pulp.LpProblem({model.name!r}, {sense})")
    lines.append(f"prob += {expression}, \"objective\"")
    for con in model.constraints:
        scope = {q.index for q in con.quants}
        qmap = {q.index: q.set_name for q in con.quants}
        loops = []
        for quant in con.quants:
            loops.append(f"for {quant.index} in {quant.set_name}:")
        body = f"prob += {_comparison(con, 'pulp', scope, qmap)}, f\"{con.name}\""
        if not loops:
            lines.append(body)
        else:
            for depth, loop in enumerate(loops):
                lines.append("    " * depth + loop)
            lines.append("    " * len(loops) + body.replace(f"f\"{con.name}\"", "f\"" + con.name + "_" + "{" + ",".join(q.index for q in con.quants) + "}\""))
    lines.extend(
        [
            "status = prob.solve(pulp.PULP_CBC_CMD(msg=False))",
            "objective_value = pulp.value(prob.objective)",
            "solution = {var.name: var.varValue for var in prob.variables()}",
            "",
        ]
    )
    return "\n".join(lines)


def _ortools(model: Model) -> str:
    lines = [
        '"""Generated by Axiom. Solves with OR-Tools SCIP."""',
        "from ortools.linear_solver import pywraplp",
        "",
        'solver = pywraplp.Solver.CreateSolver("SCIP")',
        "inf = solver.infinity()",
    ]
    lines.extend(_python_sets(model))
    lines.extend(_prev_python(model))
    lines.extend(_python_params(model))
    for decl in model.variables.values():
        low = "-inf" if decl.lower is None else _num(decl.lower)
        up = "inf" if decl.upper is None else _num(decl.upper)
        ctor = "IntVar" if decl.domain in {"integer", "binary"} else "NumVar"
        if decl.domain == "binary":
            low = "0" if decl.lower is None else _num(decl.lower)
            up = "1" if decl.upper is None else _num(decl.upper)
        if not decl.index_sets:
            lines.append(f'{decl.name} = solver.{ctor}({low}, {up}, "{decl.name}")')
        else:
            lines.append(f"{decl.name} = {{}}")
            lines.extend(_loops(decl.index_sets))
            key = _key([_index_name(name) for name in decl.index_sets])
            indent = "    " * len(decl.index_sets)
            lines.append(f'{indent}{decl.name}[{key}] = solver.{ctor}({low}, {up}, f"{decl.name}_{{{key}}}")')
    obj_sense, expression = _objective(model, "ortools")
    method = "Maximize" if obj_sense == "maximize" else "Minimize"
    lines.append(f"solver.{method}({expression})")
    for con in model.constraints:
        scope = {q.index for q in con.quants}
        qmap = {q.index: q.set_name for q in con.quants}
        statement = f"solver.Add({_comparison(con, 'ortools', scope, qmap)})"
        if not con.quants:
            lines.append(statement)
            continue
        for depth, quant in enumerate(con.quants):
            lines.append("    " * depth + f"for {quant.index} in {quant.set_name}:")
        lines.append("    " * len(con.quants) + statement)
    lines.extend(
        [
            "status_code = solver.Solve()",
            "status = solver.Solve.__doc__",
            "objective_value = solver.Objective().Value()",
            "solution = {}",
        ]
    )
    # solution extraction is target-specific; overwrite the placeholder status line
    lines = [line for line in lines if line != "status = solver.Solve.__doc__"]
    lines.append("OPTIMAL = pywraplp.Solver.OPTIMAL")
    lines.append("")
    return "\n".join(lines)


def _cvxpy(model: Model) -> str:
    lines = [
        '"""Generated by Axiom. Solves with CVXPY."""',
        "import cvxpy as cp",
        "",
    ]
    lines.extend(_python_sets(model))
    lines.extend(_prev_python(model))
    lines.extend(_python_params(model))
    lines.append("constraints = []")
    for decl in model.variables.values():
        flags = ""
        if decl.domain == "binary":
            flags = ", boolean=True"
        elif decl.domain == "integer":
            flags = ", integer=True"
        if not decl.index_sets:
            lines.append(f"{decl.name} = cp.Variable(name={decl.name!r}{flags})")
            _bound_constraints(lines, decl.name, decl.lower, decl.upper, "cvxpy")
        else:
            lines.append(f"{decl.name} = {{}}")
            lines.extend(_loops(decl.index_sets))
            key = _key([_index_name(name) for name in decl.index_sets])
            indent = "    " * len(decl.index_sets)
            lines.append(f"{indent}{decl.name}[{key}] = cp.Variable(name=f\"{decl.name}_{{{key}}}\"{flags})")
            _bound_constraints(lines, f"{decl.name}[{key}]", decl.lower, decl.upper, "cvxpy", indent)
    obj_sense, expression = _objective(model, "cvxpy")
    ctor = "cp.Maximize" if obj_sense == "maximize" else "cp.Minimize"
    lines.append(f"objective = {ctor}({expression})")
    for con in model.constraints:
        scope = {q.index for q in con.quants}
        qmap = {q.index: q.set_name for q in con.quants}
        statement = f"constraints.append({_comparison(con, 'cvxpy', scope, qmap)})"
        if not con.quants:
            lines.append(statement)
            continue
        for depth, quant in enumerate(con.quants):
            lines.append("    " * depth + f"for {quant.index} in {quant.set_name}:")
        lines.append("    " * len(con.quants) + statement)
    lines.extend(["problem = cp.Problem(objective, constraints)", "problem.solve()", "objective_value = problem.value", ""])
    return "\n".join(lines)


def _ampl(model: Model) -> str:
    lines = [f"# Axiom export: {model.name}"]
    for decl in model.sets.values():
        body = " ".join(_ampl_element(item) for item in decl.elements)
        lines.append(f"set {decl.name} := {body};")
    for decl in model.parameters.values():
        if not decl.index_sets:
            lines.append(f"param {decl.name} := {_num(decl.values.get((), 0.0))};")
            continue
        index = ", ".join(decl.index_sets)
        lines.append(f"param {decl.name} {{{index}}};")
    for decl in model.variables.values():
        index = "" if not decl.index_sets else "{" + ", ".join(decl.index_sets) + "}"
        bounds = _ampl_bounds(decl.lower, decl.upper)
        kind = " binary" if decl.domain == "binary" else " integer" if decl.domain == "integer" else ""
        lines.append(f"var {decl.name}{index}{kind}{bounds};")
    sense, expression = _objective(model, "ampl")
    lines.append(f"{sense} objective: {expression};")
    for con in model.constraints:
        quant = ""
        if con.quants:
            quant = " {" + ", ".join(f"{q.index} in {q.set_name}" for q in con.quants) + "}"
        scope = {q.index for q in con.quants}
        qmap = {q.index: q.set_name for q in con.quants}
        lines.append(f"s.t. {con.name}{quant}: {_comparison(con, 'ampl', scope, qmap)};")
    lines.append("data;")
    for decl in model.parameters.values():
        if not decl.index_sets:
            continue
        entries = []
        for key, value in decl.values.items():
            rendered = " ".join(_ampl_element(part) for part in key)
            entries.append(f"{rendered} {_num(value)}")
        lines.append(f"param {decl.name} := {' '.join(entries)};")
    lines.append("")
    return "\n".join(lines)


def _gams(model: Model) -> str:
    lines = [f"$title {model.name}", "* Generated by Axiom"]
    for decl in model.sets.values():
        body = ", ".join(_gams_element(item) for item in decl.elements)
        lines.append(f"Set {decl.name} /{body}/;")
    for decl in model.parameters.values():
        if not decl.index_sets:
            lines.append(f"Scalar {decl.name} /{_num(decl.values.get((), 0.0))}/;")
            continue
        index = ", ".join(decl.index_sets)
        entries = ", ".join(
            f"{'.'.join(_gams_element(part) for part in key)} {_num(value)}" for key, value in decl.values.items()
        )
        lines.append(f"Parameter {decl.name}({index}) /{entries}/;")
    lines.append("Variables " + ", ".join([*(decl.name for decl in model.variables.values()), "axiom_obj"]) + ";")
    for decl in model.variables.values():
        if decl.domain == "binary":
            lines.append(f"Binary Variable {decl.name};")
        elif decl.domain == "integer":
            lines.append(f"Integer Variable {decl.name};")
        elif decl.lower is not None and decl.lower >= 0 and decl.domain == "continuous":
            lines.append(f"Positive Variable {decl.name};")
        if decl.lower is not None:
            lines.append(f"{decl.name}.lo({_gams_domain(decl.index_sets)}) = {_num(decl.lower)};".replace("()", ""))
        if decl.upper is not None:
            lines.append(f"{decl.name}.up({_gams_domain(decl.index_sets)}) = {_num(decl.upper)};".replace("()", ""))
    lines.append("Equations objective" + "".join(f", {con.name}" for con in model.constraints) + ";")
    sense, expression = _objective(model, "gams")
    lines.append(f"objective.. axiom_obj =e= {expression};")
    for con in model.constraints:
        domain = ""
        if con.quants:
            domain = "(" + ", ".join(q.index for q in con.quants) + ")"
        scope = {q.index for q in con.quants}
        qmap = {q.index: q.set_name for q in con.quants}
        lines.append(f"{con.name}{domain}.. {_gams_relation(_comparison(con, 'gams', scope, qmap))};")
    gams_sense = "maximizing" if sense == "maximize" else "minimizing"
    kind = "mip" if any(var.domain != "continuous" for var in model.variables.values()) else "lp"
    if _nonlinear(model):
        kind = "nlp"
    lines.append(f"Model axiom /all/;")
    lines.append(f"Solve axiom using {kind} {gams_sense} axiom_obj;")
    lines.append("")
    return "\n".join(lines)


def _jump(model: Model) -> str:
    lines = [
        f"# Generated by Axiom from {model.name}",
        "using JuMP, HiGHS",
        "model = Model(HiGHS.Optimizer)",
    ]
    lines.extend(_python_sets(model, julia=True))
    lines.extend(_prev_julia(model))
    for decl in model.parameters.values():
        if not decl.index_sets:
            lines.append(f"{decl.name} = {_num(decl.values.get((), 0.0))}")
        else:
            pairs = ", ".join(f"{_julia_key(key)} => {_num(value)}" for key, value in decl.values.items())
            lines.append(f"{decl.name} = Dict({pairs})")
    for decl in model.variables.values():
        bounds = _jump_bounds(decl.lower, decl.upper)
        kind = ", Int" if decl.domain == "integer" else ", Bin" if decl.domain == "binary" else ""
        if not decl.index_sets:
            lines.append(f"@variable(model, {bounds[0]}{decl.name}{bounds[1]}{kind})")
        else:
            iterator = ", ".join(f"{_index_name(name)} in {name}" for name in decl.index_sets)
            lines.append(f"@variable(model, {bounds[0]}{decl.name}[{iterator}]{bounds[1]}{kind})")
    obj_sense, expression = _objective(model, "jump")
    jump_sense = "Max" if obj_sense == "maximize" else "Min"
    lines.append(f"@objective(model, {jump_sense}, {expression})")
    for con in model.constraints:
        scope = {q.index for q in con.quants}
        qmap = {q.index: q.set_name for q in con.quants}
        if con.quants:
            iterator = ", ".join(f"{q.index} in {q.set_name}" for q in con.quants)
            lines.append(f"@constraint(model, {con.name}[{iterator}], {_comparison(con, 'jump', scope, qmap)})")
        else:
            lines.append(f"@constraint(model, {con.name}, {_comparison(con, 'jump', scope, qmap)})")
    lines.extend(["optimize!(model)", "objective_value = objective_value(model)", ""])
    return "\n".join(lines)


def _objective(model: Model, target: str) -> tuple[str, str]:
    if not model.objectives:
        raise AxiomError("导出需要至少一个目标。", "Export requires an objective.", code="no_objective")
    if len(model.objectives) == 1:
        obj = model.objectives[0]
        return obj.sense, _emit(obj.expr, target, set(), {})
    parts = []
    for obj in model.objectives:
        sign = "" if obj.sense == "minimize" else "-"
        weight = "" if abs(obj.weight - 1) < 1e-12 else f"{_num(obj.weight)} * "
        parts.append(f"({sign}{weight}({_emit(obj.expr, target, set(), {})}))")
    joiner = " + "
    return "minimize", joiner.join(parts)


def _comparison(con, target: str, scope: set[str], qmap: dict[str, str]) -> str:
    left = _emit(con.lhs, target, scope, qmap)
    right = _emit(con.rhs, target, scope, qmap)
    if target == "gams":
        relation = {"<=": "=l=", ">=": "=g=", "==": "=e="}[con.relation]
        return f"{left} {relation} {right}"
    return f"({left}) {con.relation} ({right})"


def _gams_relation(text: str) -> str:
    return text


def _emit(expr: Expr, target: str, scope: set[str], qmap: dict[str, str]) -> str:
    if expr.op == "const":
        return _num(float(expr.value or 0.0))
    if expr.op == "neg":
        return f"(-{_emit(expr.args[0], target, scope, qmap)})"
    if expr.op == "sum":
        inner_scope = set(scope) | {q.index for q in expr.quants}
        inner_map = dict(qmap)
        inner_map.update({q.index: q.set_name for q in expr.quants})
        body = _emit(expr.args[0], target, inner_scope, inner_map)
        return _sum(expr.quants, body, target)
    if expr.op in {"add", "sub", "mul", "div", "pow"}:
        left = _emit(expr.args[0], target, scope, qmap)
        right = _emit(expr.args[1], target, scope, qmap)
        symbol = {"add": "+", "sub": "-", "mul": "*", "div": "/", "pow": _pow(target)}[expr.op]
        if expr.op == "pow" and target == "gams":
            return f"power({left}, {right})"
        return f"({left} {symbol} {right})"
    if expr.op == "ref":
        return _ref(expr, target, scope, qmap)
    raise AxiomError(f"无法导出算子 {expr.op}。", f"Cannot export operator {expr.op}.", code="bad_expr")


def _pow(target: str) -> str:
    if target in _PYTHON:
        return "**"
    return "^"


def _sum(quants: tuple[Quantifier, ...], body: str, target: str) -> str:
    if target == "ampl":
        joined = ", ".join(f"{q.index} in {q.set_name}" for q in quants)
        return f"(sum {{{joined}}} {body})"
    if target == "gams":
        joined = ", ".join(q.index for q in quants)
        return f"sum(({joined}), {body})"
    if target == "jump":
        gens = ", ".join(f"{q.index} in {q.set_name}" for q in quants)
        return f"sum({body} for {gens})"
    gens = " ".join(f"for {q.index} in {_set_ref(q.set_name, target)}" for q in quants)
    fn = "pulp.lpSum" if target == "pulp" else "sum"
    return f"{fn}({body} {gens})"


def _ref(expr: Expr, target: str, scope: set[str], qmap: dict[str, str]) -> str:
    name = expr.name or "x"
    if not expr.indices:
        if name in scope and target not in {"ampl", "gams"}:
            return name
        if target == "pyomo":
            return f"m.{name}"
        return name
    rendered = [_emit_index(index, target, scope, qmap) for index in expr.indices]
    if target == "pyomo":
        return f"m.{name}[{', '.join(rendered)}]"
    if target == "ampl":
        return f"{name}[{','.join(rendered)}]"
    if target == "gams":
        return f"{name}({', '.join(rendered)})"
    if target == "jump":
        return f"{name}[{', '.join(rendered)}]"
    if len(rendered) == 1:
        return f"{name}[{rendered[0]}]"
    return f"{name}[{', '.join(rendered)}]" if False else f"{name}[({', '.join(rendered)})]"


def _emit_index(index, target: str, scope: set[str], qmap: dict[str, str]) -> str:
    if index.kind == "literal":
        return _element(index.value, target)
    if index.kind == "symbol":
        if index.value in scope:
            return index.value
        return _element(index.value, target)
    if index.kind == "offset":
        base = index.value if index.value in scope else _element(index.value, target)
        if index.offset < 0:
            return f"({base} - {-index.offset})"
        return f"({base} + {index.offset})"
    if index.kind == "prev":
        set_name = qmap.get(index.value, "S")
        symbol = index.value if index.value in scope else _element(index.value, target)
        if target == "pyomo":
            return f"_prev_{set_name}[{symbol}]"
        if target == "gams":
            return f"prev_{set_name}({symbol})"
        return f"_prev_{set_name}[{symbol}]"
    return index.value


def _python_sets(model: Model, julia: bool = False) -> list[str]:
    lines = []
    for decl in model.sets.values():
        lines.append(f"{decl.name} = {_pylist(decl.elements)}")
    return lines


def _python_params(model: Model) -> list[str]:
    lines = []
    for decl in model.parameters.values():
        if not decl.index_sets:
            lines.append(f"{decl.name} = {_num(decl.values.get((), 0.0))}")
        else:
            lines.append(f"{decl.name} = {_pydict(decl.values)}")
    return lines


def _prev_python(model: Model) -> list[str]:
    lines = []
    for decl in model.sets.values():
        pairs = []
        previous = None
        for element in decl.elements:
            pairs.append(f"{_py(element)}: {_py(previous) if previous is not None else 'None'}")
            previous = element
        lines.append(f"_prev_{decl.name} = {{{', '.join(pairs)}}}")
    return lines


def _prev_pyomo(model: Model) -> list[str]:
    return _prev_python(model)


def _prev_julia(model: Model) -> list[str]:
    lines = []
    for decl in model.sets.values():
        pairs = []
        previous = None
        for element in decl.elements:
            if previous is not None:
                pairs.append(f"{_py(element)} => {_py(previous)}")
            previous = element
        lines.append(f"_prev_{decl.name} = Dict({', '.join(pairs)})")
    return lines


def _loops(set_names: list[str]) -> list[str]:
    return ["    " * depth + f"for {_index_name(name)} in {name}:" for depth, name in enumerate(set_names)]


def _index_name(set_name: str) -> str:
    return "i_" + set_name


def _key(names: list[str]) -> str:
    if len(names) == 1:
        return names[0]
    return "(" + ", ".join(names) + ")"


def _bound_constraints(lines, name, lower, upper, target, indent=""):
    if lower is not None:
        lines.append(f"{indent}constraints.append({name} >= {_num(lower)})")
    if upper is not None:
        lines.append(f"{indent}constraints.append({name} <= {_num(upper)})")


def _set_ref(name: str, target: str) -> str:
    if target == "pyomo":
        return f"m.{name}"
    return name


def _pylist(elements: list[str]) -> str:
    return "[" + ", ".join(_py(item) for item in elements) + "]"


def _pydict(values: dict) -> str:
    parts = []
    for key, value in values.items():
        if len(key) == 1:
            rendered = _py(key[0])
        else:
            rendered = "(" + ", ".join(_py(part) for part in key) + ")"
        parts.append(f"{rendered}: {_num(value)}")
    return "{" + ", ".join(parts) + "}"


def _py(value: str | None) -> str:
    if value is None:
        return "None"
    if _is_int(value):
        return str(int(value))
    return repr(value)


def _element(value: str, target: str) -> str:
    if target in _PYTHON or target == "jump":
        return _py(value)
    if target == "ampl":
        return _ampl_element(value)
    if target == "gams":
        return _gams_element(value)
    return _py(value)


def _ampl_element(value: str) -> str:
    if value.isidentifier() or _is_int(value):
        return value
    return "'" + value.replace("'", "\\'") + "'"


def _gams_element(value: str) -> str:
    if value.isidentifier() or _is_int(value):
        return value
    return "'" + value.replace("'", "''") + "'"


def _ampl_bounds(lower, upper) -> str:
    parts = []
    if lower is not None:
        parts.append(f" >= {_num(lower)}")
    if upper is not None:
        parts.append(f" <= {_num(upper)}")
    return "".join(parts)


def _jump_bounds(lower, upper) -> tuple[str, str]:
    left = "" if lower is None else f"{_num(lower)} <= "
    right = "" if upper is None else f" <= {_num(upper)}"
    return left, right


def _gams_domain(index_sets: list[str]) -> str:
    return ", ".join(index_sets)


def _julia_key(key: tuple[str, ...]) -> str:
    if len(key) == 1:
        return _py(key[0])
    return "(" + ", ".join(_py(part) for part in key) + ")"


def _num(value: float) -> str:
    if float(value).is_integer() and abs(value) < 1e15:
        return str(int(value))
    return format(float(value), ".12g")


def _is_int(value: str) -> bool:
    token = value[1:] if value.startswith("-") else value
    return token.isdigit()
